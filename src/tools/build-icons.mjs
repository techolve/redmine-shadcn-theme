const missing = [];
const symbols = Object.entries(ICONS).map(([redmine, lucide]) => {
  let svg;
  try {
    svg = readFileSync(join(lucideDir, `${lucide}.svg`), 'utf8');
  } catch {
    missing.push(`${redmine} -> ${lucide}`);
    return '';
  }
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('');
  return `<symbol viewBox="0 0 24 24" stroke-linecap="round" stroke-linejoin="round" id="icon--${redmine}">${inner}</symbol>`;
});

if (missing.length) {
  console.error(`Lucide に存在しないアイコン:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const sprite = `<?xml version="1.0"?>
<!-- Generated by src/tools/build-icons.mjs from lucide-static v${version} (ISC License, https://lucide.dev) -->
<svg xmlns="http://www.w3.org/2000/svg" class="icon--sprite"><defs>
${symbols.join('\n')}
</defs></svg>
`;

mkdirSync('images', { recursive: true });
writeFileSync('images/icons.svg', sprite);
console.log(`images/icons.svg: ${symbols.length} icons`);
